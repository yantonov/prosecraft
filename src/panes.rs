    #[test]
    fn the_debug_ring_buffer_stops_at_its_capacity() {
        let mut state = StreamState::new();
        state.spawn(Instant::now());
        for n in 0..DEBUG_CAPACITY + 500 {
            state.app(format!("line{n}"));
        }

        let debug = state.debug_text();
        assert_eq!(
            debug.lines().count(),
            DEBUG_CAPACITY,
            "the ring buffer grew past its bound"
        );
        // The oldest lines are the ones dropped, so the newest is still there.
        assert!(!debug.lines().any(|line| line.ends_with("line0")));
        assert!(debug.contains(&format!("line{}", DEBUG_CAPACITY + 499)));
    }

