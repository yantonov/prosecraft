    #[test]
    fn a_thousand_events_are_one_pass_not_a_thousand() {
        // The batching rule (spec §6.1b) is a property of the API: `ingest` takes a slice, so
        // a caller cannot write per event without first collecting them.
        let mut state = StreamState::new();
        state.spawn(Instant::now());
        let lines: Vec<Line> = (0..1000).map(|n| text_delta(&format!("d{n}"))).collect();
        state.ingest(&lines, &Claude);

        let debug = state.debug_text();
        assert!(debug.contains("d0"));
        assert!(debug.contains("d999"));
    }

