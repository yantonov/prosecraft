//! What the two read-only panes contain, and how the stream reaches them (spec §5, §6.1b,
//! §7).
//!
//! The split this module enforces is the one the whole design exists for: the **debug pane**
//! receives every line the harness produced, labelled by origin, while the **output pane** is
//! written exactly once per run, from the terminal event, and only when the run succeeded.
//! Nothing else can reach the output pane, so a reasoning delta, a half-emitted fence or a
//! stderr diagnostic can never be mistaken for the rewrite.
//!
//! That is also why the final text is held as *pending* rather than written when it arrives.
//! A `result` event that carries a diagnostic, or a run that then exits non-zero, has to
//! leave the output pane as it was cleared on spawn; committing on arrival would display a
//! rewrite that the run itself rejected.
//!
//! Scrolling is in **visual rows**, not lines, because both panes wrap and a page has to mean
//! a screenful. Rows depend on the pane's width, so the geometry of the last draw is cached:
//! a paging key arrives between draws and cannot know the width otherwise. Nothing here
//! interprets markdown (spec §6.1b), so a line is drawn as exactly the characters it holds.

// The tick loop that drains the process into `ingest`/`settle` is the `rewrite-flow` ticket,
// so those have no caller yet. The attribute goes away with it.
#![allow(dead_code)]

use std::cell::Cell;
use std::collections::VecDeque;
use std::time::{Duration, Instant};

use ratatui::Frame;
use ratatui::layout::Rect;
use ratatui::style::Style;

use crate::harness::{Event, HarnessAdapter};
