    #[test]
    fn scrolling_past_the_top_clamps_instead_of_underflowing() {
        let mut state = StreamState::new();
        state.spawn(Instant::now());
        for n in 0..10 {
            state.app(format!("line{n}"));
        }
        drawn(&state, Focus::Debug, 20, 4);

        for _ in 0..50 {
            state.page(Focus::Debug, -1);
            state.scroll(Focus::Debug, -1);
        }
        let rows = drawn(&state, Focus::Debug, 20, 4);
        // Still showing real content, with the first line at the top: the spawn's own
        // "run started" note, because the top of this buffer is where the view clamped to.
        assert!(rows[0].contains("app   run started"), "{rows:?}");
    }
